import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const roots = ['pages', 'src', 'tests', 'scripts'];
const rootFiles = ['README.md', 'eslint.config.mjs', 'playwright.config.ts',
  'tsconfig.json', 'vitest.config.ts', 'package.json'];
const excluded = new Map([
  ['package-lock.json', 'dependency lock generated by npm'],
  ['docs/', 'documentation is checked by review, not source gates'],
  ['.next/', 'Next generated output'],
  ['coverage/', 'test generated output'],
]);

export function countPhysicalLines(content) {
  const bytes = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (!bytes.length) return 0;
  let count = 0;
  for (let index = 0; index < bytes.length; index += 1) {
    if (bytes[index] === 10 || (bytes[index] === 13 && bytes[index + 1] !== 10)) count += 1;
  }
  const last = bytes[bytes.length - 1];
  return last === 10 || last === 13 ? count : count + 1;
}

function parseArgs(argv) {
  const options = { root: process.cwd(), files: null, json: false };
  for (let index = 0; index < argv.length; index += 1) {
    const value = argv[index];
    if (value === '--root') options.root = resolve(argv[++index]);
    if (value === '--files') options.files = argv[++index].split(',').filter(Boolean);
    if (value === '--json') options.json = true;
  }
  return options;
}

function walk(directory, result) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) walk(path, result);
    else result.push(path);
  }
}

function defaultFiles(root) {
  const paths = rootFiles.map((file) => join(root, file));
  for (const directory of roots) {
    const path = join(root, directory);
    if (statSync(path, { throwIfNoEntry: false })?.isDirectory()) walk(path, paths);
  }
  return paths;
}

function exclusion(path) {
  const normalized = path.replaceAll('\\', '/');
  return [...excluded.entries()].find(([prefix]) => normalized === prefix || normalized.startsWith(prefix));
}

function inspect(root, paths) {
  const files = [];
  const failures = [];
  for (const candidate of paths) {
    const path = resolve(root, candidate);
    const name = relative(root, path).replaceAll('\\', '/');
    const reason = exclusion(name);
    if (reason) {
      files.push({ path: name, status: 'excluded', reason: reason[1] });
      continue;
    }
    try {
      const lines = countPhysicalLines(readFileSync(path));
      const status = lines > 99 ? 'fail' : 'pass';
      files.push({ path: name, lines, status });
      if (status === 'fail') failures.push(`${name}: ${lines} lines (maximum 99)`);
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      files.push({ path: name, status: 'error', error: message });
      failures.push(`${name}: unreadable (${message})`);
    }
  }
  return { files, failures };
}

export function runLineCheck(root = process.cwd(), files) {
  const paths = files ?? defaultFiles(root).map((path) => relative(root, path));
  return inspect(root, paths);
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  const report = runLineCheck(options.root, options.files);
  if (options.json) console.log(JSON.stringify(report));
  else report.files.forEach((file) => console.log(`${file.status.toUpperCase()} ${file.path}${file.lines === undefined ? '' : ` (${file.lines})`}`));
  report.failures.forEach((failure) => console.error(`FAIL ${failure}`));
  process.exitCode = report.failures.length ? 1 : 0;
}

if (import.meta.url === `file://${process.argv[1]}`) main();
